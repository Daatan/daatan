"""Build src/lib/utils/outlet-profiles.json from collect.py's raw.json and curation.json (daatan#2345).

Usage: python3 -I build.py raw.json curation.json src/lib/utils/outlet-profiles.json review.md
Offline. review.md lists every hand decision and every lead that characterises an outlet.
"""
import json, re, sys
raw_path, cur_path, out_json, out_review = sys.argv[1:5]
LANGS = ["en", "he", "ru", "eo"]
ORDER = ["founded", "country", "headquarters", "language", "owner"]
raw = json.load(open(raw_path, encoding="utf-8")); cur = json.load(open(cur_path, encoding="utf-8"))
labels = raw["labels"]

# Shown under a "Language" heading, so "английский язык" / "angla lingvo" says "language" twice.
LANGUAGE_SUFFIX = {"ru": " язык", "eo": " lingvo"}

def label(q, fact=None):
    lab = {l: labels.get(q, {}).get(l) for l in LANGS}
    lab = {l: v for l, v in lab.items() if v}
    assert "en" in lab, f"no en label for {q}"
    if fact == "language":
        lab = {l: v.removesuffix(LANGUAGE_SUFFIX.get(l, "\0")) for l, v in lab.items()}
    return lab

out, log = {}, {}
for dom, r in raw["outlets"].items():
    notes = log.setdefault(dom, [])
    facts, sources = {}, []
    for name, vals in r["facts"].items():
        keep = next((k["values"] for k in cur["keep_only"] if k["outlet"] == dom and k["fact"] == name), None)
        if any(o["outlet"] == dom and o["fact"] == name for o in cur["omit"]):
            notes.append(f"omit {name}: " + next(o["reason"] for o in cur["omit"] if o["outlet"] == dom and o["fact"] == name)); continue
        if name == "founded":
            years = sorted({int(v["time"][1:5]) for v in vals if v["precision"] >= 9})
            if keep: years = [int(y) for y in keep]; notes.append(f"founded kept {keep}")
            if len(years) != 1: notes.append(f"founded ambiguous {years}, omitted"); continue
            facts["founded"] = years[0]
        else:
            if keep: vals = [v for v in vals if v in keep]; notes.append(f"{name} kept {keep}")
            facts[name] = [label(v, name) for v in vals]
    if facts: sources.append(f"https://www.wikidata.org/wiki/{r['qid']}")
    for a in (a for a in cur["add"] if a["outlet"] == dom):
        if "year" in a: facts[a["fact"]] = a["year"]
        else: facts.setdefault(a["fact"], []).append(label(a["qid"], a["fact"]) if "qid" in a else a["label"])
        if a["source"] not in sources: sources.append(a["source"])
        notes.append(f"add {a['fact']}: {a['reason']}")
    wiki, links = {}, {}
    for lang, x in r["extracts"].items():
        # The header's Wikipedia button (daatan#2349) links every article that is the outlet's own,
        # including ones whose lead is dropped below as stale. An article that resolves to another
        # item (enwiki "Ynet" -> Yedioth Ahronoth) is someone else's article, so it gets no link.
        if x["wikibase_item"] == r["qid"]: links[lang] = x["url"]
        else: notes.append(f"no {lang} link: {x['requested']!r} resolves to {x['wikibase_item']}, not {r['qid']}")
        drop = next((d for d in cur["drop_extract"] if d["outlet"] == dom and d["lang"] == lang), None)
        if drop: notes.append(f"drop {lang} paragraph: {drop['reason']}"); continue
        assert x["wikibase_item"] == r["qid"], (dom, lang)
        wiki[lang] = {"text": x["text"], "url": x["url"], "revision": x["revision"]}
    rec = {}
    if r["qid"]: rec["wikidata"] = r["qid"]
    if facts: rec["facts"] = {k: facts[k] for k in ORDER if k in facts}; rec["factSources"] = sources
    if wiki: rec["wikipedia"] = {l: wiki[l] for l in LANGS if l in wiki}
    if links: rec["wikipediaLinks"] = {l: links[l] for l in LANGS if l in links}
    if dom in cur["researched"]:
        rec["researched"] = [{"text": {l: s[l] for l in LANGS if l in s}, "sources": s["sources"]} for s in cur["researched"][dom]]
    if rec.get("facts") or rec.get("wikipedia") or rec.get("wikipediaLinks") or rec.get("researched"):
        out[dom] = rec

json.dump(dict(sorted(out.items())), open(out_json, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
open(out_json, "a", encoding="utf-8").write("\n")

# ---- review table ----
FLAG = re.compile(r"far-right|far-left|right-wing|left-wing|anti-|state-run|state-funded|state-owned|propaganda|centris|conservative|liberal|"
                  r"лево|право|пропаганд|государствен|ימין|שמאל|ממשלתית|שמרנ|ŝtat|centrism", re.I)
def about(rec, loc):
    w = rec.get("wikipedia", {})
    if loc in w: return f"Wikipedia {loc}"
    if "en" in w: return "Wikipedia en (fallback)"
    rs = rec.get("researched")
    if rs: return "researched " + (loc if all(loc in s["text"] for s in rs) else "en")
    return "—"
L = ["# Outlet profiles review: daatan#2345", "",
     "Generated by `scripts/outlet-profiles/build.py` from Wikidata and Wikipedia, plus `curation.json` (hand decisions, each with its reason).", "",
     "## 1. Paragraphs that characterise the outlet",
     "These are Wikipedia's own words, shown unmodified with attribution. They are listed so you can decide before merge whether to show them.", ""]
for dom, rec in out.items():
    for lang, x in rec.get("wikipedia", {}).items():
        for m in FLAG.finditer(x["text"]):
            s = x["text"]; i = m.start()
            L.append(f"- **{dom}** ({lang}): …{s[max(0, i-90):i+90].strip()}… [article]({x['url']})".replace("\n", " ")); break
L += ["", "## 2. Per outlet", "", "| outlet | facts (en) | about: en / he / ru / eo | Wikipedia links | hand decisions |", "|---|---|---|---|---|"]
for dom in sorted(raw["outlets"]):
    rec = out.get(dom, {})
    f = rec.get("facts", {})
    fs = "; ".join(f"{k}: " + (str(v) if isinstance(v, int) else ", ".join(x["en"] for x in v)) for k, v in f.items()) or "—"
    ab = " / ".join(about(rec, l) for l in LANGS) if rec else "nothing shown"
    wl = ", ".join(f"[{l}]({u})" for l, u in rec.get("wikipediaLinks", {}).items()) or "—"
    L.append(f"| {dom} | {fs} | {ab} | {wl} | {'<br>'.join(log.get(dom, [])) or '—'} |")
L += ["", "## 3. Researched text (Daatan's own wording)", ""]
for dom, rec in out.items():
    for s in rec.get("researched", []):
        L.append(f"- **{dom}**: {s['text']['en']} — sources: " + ", ".join(s["sources"]))
L += ["", "## 4. Every paragraph shown, by language", ""]
for lang in LANGS:
    L += [f"### {lang}", ""]
    for dom, rec in out.items():
        x = rec.get("wikipedia", {}).get(lang)
        if x: L.append(f"**{dom}** ([article]({x['url']}), {len(x['text'])} chars): {x['text']}\n")
open(out_review, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(len(out), "profiles")
